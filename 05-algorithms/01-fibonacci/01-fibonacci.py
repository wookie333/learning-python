"""
Задача 1. Небольшое число Фибоначчи

Условие:
Дано целое число n. Необходимо вычислить n-е число
Фибоначчи.

F(0) = 0, F(1) = 1
F(n) = F(n-1) + F(n-2)

Ограничения:
1 <= n <= 40

Пример:
Ввод: 3
Вывод: 2

Сложность:
Время — O(n)
Память — O(1)
"""


def fib(n):
    a, b = 0, 1

    for i in range(n):
        a, b = b, a + b

    return a


def main():
    n = int(input())
    print(fib(n))


if __name__ == "__main__":
    main()
