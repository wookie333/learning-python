"""
Задача 2. Последняя цифра большого числа Фибоначчи

Условие:
Дано целое число n. Необходимо найти последнюю
цифру n-го числа Фибоначчи.

Ограничения:
1 <= n <= 10^7

Пример:
Ввод: 841645
Вывод: 5

Идея:
Вместо вычисления огромных чисел Фибоначчи
храним только их последние цифры.

Сложность:
Время — O(n)
Память — O(1)
"""


def fib_digit(n):
    a, b = 0, 1

    for i in range(n):
        a, b = b, (a + b) % 10

    return a


def main():
    n = int(input())
    print(fib_digit(n))


if __name__ == "__main__":
    main()
