"""
Задача 4. Наибольший общий делитель

Условие:
Даны два целых числа a и b.
Необходимо найти их наибольший общий делитель.

Ограничения:
1 <= a, b <= 2 * 10^9

Пример 1:
Ввод: 18 35
Вывод: 1

Пример 2:
Ввод: 14159572 63967072
Вывод: 4

Идея:
Используем алгоритм Евклида:

gcd(a, b) = gcd(b, a % b)

Когда b становится равным нулю,
возвращаем a.

Сложность:
Время — O(log(min(a, b)))
Память — O(log(min(a, b)))
"""


def gcd(a, b):
    if b == 0:
        return a

    return gcd(b, a % b)


def main():
    a, b = map(int, input().split())
    print(gcd(a, b))


if __name__ == "__main__":
    main()
