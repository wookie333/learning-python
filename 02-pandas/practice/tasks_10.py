import numpy as np
import pandas as pd

df = pd.DataFrame({
    'age': [53, np.nan, 11, 18, 7],
    'name': ['Сергей', 'Маша', 'Ксюша', 'Аристарх', 'Соня'],
    'наличие авто': [True, True, False, np.nan, False],
    'марка авто': [np.nan, np.nan, np.nan, np.nan, np.nan]
})


# Задача 1
# Удалить строки, в которых отсутствует возраст.
# Пропуски в остальных столбцах не учитываются.
# Решение разобрали вместе.

print(df.dropna(subset=['age']), '\n')


# Задача 2
# Заполнить пропущенный возраст значением 25.
# Пропуски в столбце «наличие авто» заполнить False.
# Столбец «марка авто» не изменять.

print(df.fillna(value={
    'age': 25,
    'наличие авто': False
}), '\n')


# Задача 3
# Удалить столбцы, в которых все значения — NaN.
# Столбцы с хотя бы одним настоящим значением оставить.

print(df.dropna(how='all', axis=1), '\n')


# Задача 4
# Вывести людей, у которых возраст известен
# и точно нет автомобиля.
# Использовать булевы маски и notna().
# Исправлено после проверки.

print(df[
    (df['age'].notna()) &
    (df['наличие авто'] == False)
], '\n')


# Дополнительная проверка
# Удалить строки, где есть пропуски
# в age ИЛИ в «наличие авто».
# Пропуски в «марка авто» не учитывать.

print(df.dropna(subset=['age', 'наличие авто']))

