import pandas as pd

df = pd.DataFrame({
    'age': [53, 37, 11, 18, 7],
    'name': ['Сергей', 'Маша', 'Ксюша', 'Аристарх', 'Соня'],
    'has car': [True, True, False, True, False]
})


# Задача 1
# Вывести людей, у которых есть машина
# и возраст строго больше 30 лет.
# Решить через булевую маску и через query().

print(df[(df['has car']) & (df['age'] > 30)])
print(df.query('age > 30 and `has car`'), '\n')


# Задача 2
# Через isin() вывести людей, чей возраст
# равен 7, 11 или 37.

print(df[df['age'].isin([7, 11, 37])], '\n')


# Задача 3
# Через query() вывести людей старше 10 лет,
# у которых нет машины.

print(df.query('(age > 10) and (not `has car`)'))


# Задача 4
# Есть таблица студентов.
# Выбрать тех, кто:
# 1. Живёт в Москве или Казани.
# 2. Имеет оценку не меньше 80.
# 3. Младше 22 лет.
# Использовать query().

df = pd.DataFrame({
    'name': ['Ilya', 'Max', 'Alex', 'Dima', 'Ivan'],
    'age': [19, 20, 21, 19, 22],
    'score': [85, 92, 78, 64, 90],
    'city': ['Moscow', 'Kazan', 'Moscow', 'Sochi', 'Kazan']
})

print(df.query(
    '((city == "Moscow") or (city == "Kazan")) '
    'and (score >= 80) and (age < 22)'
))

# Важно: без дополнительных скобок вокруг
# двух условий по городам логика будет неправильной.
# AND имеет более высокий приоритет, чем OR.


# Дополнительная проверка понимания
# Выбрать студентов из Москвы или Сочи
# с оценкой меньше 80.

print(df[
    (df['city'].isin(['Moscow', 'Sochi'])) &
    (df['score'] < 80)
])

